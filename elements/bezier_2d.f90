subroutine Bezier_2d(n,s,t,xx,xout)
real*8 :: xx(4,4,n)
real*8 :: xout(n)

xout(:)   =             (1.d0 - s)**3   * (             (1.d0 - t)**3 * xx(1,1,:)   &
                                        + 3.d0 * t    * (1.d0 - t)**2 * xx(1,2,:)   &
                                        + 3.d0 * t**2 * (1.d0 - t)    * xx(1,3,:)   &
                                        +        t**3                 * xx(1,4,:) ) &

          + 3.d0 * s    * (1.d0 - s)**2 * (             (1.d0 - t)**3 * xx(2,1,:)   &
                                        + 3.d0 * t    * (1.d0 - t)**2 * xx(2,2,:)   &
                                        + 3.d0 * t**2 * (1.d0 - t)    * xx(2,3,:)   &
                                        +        t**3                 * xx(2,4,:) ) &

          + 3.d0 * s**2 * (1.d0 - s)    * (             (1.d0 - t)**3 * xx(3,1,:)   &
                                        + 3.d0 * t    * (1.d0 - t)**2 * xx(3,2,:)   &
                                        + 3.d0 * t**2 * (1.d0 - t)    * xx(3,3,:)   &
                                        +        t**3                 * xx(3,4,:) ) &

          +       s**3                  * (             (1.d0 - t)**3 * xx(4,1,:)   &
                                        + 3.d0 * t    * (1.d0 - t)**2 * xx(4,2,:)   &
                                        + 3.d0 * t**2 * (1.d0 - t)    * xx(4,3,:)   &
                                        +        t**3                 * xx(4,4,:) )

return
end
