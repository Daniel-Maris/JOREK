function AMJUEL_rate_coeff_neTe(matrix_coeff,n_e,T_e) result(rate_coeff)
!calculates rate coefficient from the polynomial coefficients
    use constants, only: MU_ZERO, MASS_PROTON, ATOMIC_MASS_UNIT, K_BOLTZ, EL_CHG
    real*8, dimension(9,9), intent(in)  :: matrix_coeff
    real*8, intent(in)      :: n_e,T_e
    real*8                  :: n_e_limit,T_e_eV,T_e_eV_limit, lnsv
    real*8                      :: rate_coeff
    integer                 :: i,j

    !make sure the boundaries of the fits are respected
    T_e_eV = T_e*K_BOLTZ/EL_CHG
    n_e_limit = max(n_e,1.d14)
    n_e_limit = min(n_e_limit,1.d22)
    T_e_eV_limit = max(T_e_eV,1.d-1)
    T_e_eV_limit = min(T_e_eV_limit,1.d3)

    !loop over the coefficients
    lnsv = 0.d0
    do i=1,size(matrix_coeff(1,:)) 
        do j=1,size(matrix_coeff(:,1)) 
            lnsv = lnsv + matrix_coeff(i,j)*log(n_e_limit/(1.d14))**(j-1.d0)*log(T_e_eV_limit)**(i-1.d0) !output in cm**-3
        end do 
    end do 
    

    
    rate_coeff = exp(lnsv)/1.d6;   !sigma v in m^3 s^-1
  
end function AMJUEL_rate_coeff_neTe
